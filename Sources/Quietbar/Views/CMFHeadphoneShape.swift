/// Product artwork for a device model, falling back to an SF Symbol for devices without one.
struct ProductGlyph: View {
    let glyph: String?
    let fallbackSymbol: String

    var body: some View {
        if let shape = Self.shape(for: glyph) {
            shape
                .fill(Color(nsColor: .labelColor), style: FillStyle(eoFill: true))
                .padding(7)
        } else {
            Image(systemName: fallbackSymbol)
                .font(.system(size: 18, weight: .regular))
        }
    }

    static func shape(for glyph: String?) -> CMFHeadphoneShape? {
        glyph == "cmf.headphonePro" ? CMFHeadphoneShape() : nil
    }

    /// A template image so macOS tints it for light, dark and highlighted menu bars.
    @MainActor
    static func menuBarImage(for glyph: String?) -> NSImage? {
        guard let shape = shape(for: glyph) else { return nil }
        if let cached = menuBarCache[glyph ?? ""] { return cached }
        let height: CGFloat = 16
        let size = CGSize(width: (height * CMFHeadphoneShape.aspectRatio).rounded(.up), height: height)
        let renderer = ImageRenderer(
            content: shape.fill(Color.black, style: FillStyle(eoFill: true)).frame(
                width: size.width, height: size.height))
        renderer.scale = 3
        guard let image = renderer.nsImage else { return nil }
        image.size = size
        image.isTemplate = true
        image.accessibilityDescription = "CMF Headphone Pro"
        menuBarCache[glyph ?? ""] = image
        return image
    }

    @MainActor private static var menuBarCache: [String: NSImage] = [:]
}
